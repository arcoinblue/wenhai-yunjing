#!/usr/bin/env python3
"""Build the Rime (librime) Tangut input schemas from ../data/tangut.json.

Writes into ime/rime/:
  tangut_downes.dict.yaml   characters by Downes radical code (one Rime syllable per radical)
  tangut_ghc.dict.yaml      characters and words by Gong Hwang-cherng (GHC) reading, ASCII spelling
  tangut_gloss.txt          table read by lua/tangut_gloss.lua for candidate comments
  tangut_downes_reduced.schema.yaml   (its speller algebra is generated from the reduced groups)

Usage: python3 ime/build.py            (run from the repository root or anywhere)
"""
import json, re, unicodedata, os, collections, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, 'rime')
VERSION = '1.0'

D = json.load(open(os.path.join(ROOT, 'data', 'tangut.json'), encoding='utf-8'))
CH, WORDS, RADS, GROUPS = D['ch'], D['w'], D['rad'], D['grp']
RAD_SET = {r[0] for r in RADS}

# ---------------------------------------------------------------- GHC → ASCII
# Strict spelling (lossless).  The schema adds looser spellings with speller algebra.
#   ś sx   ź zx   ń nx   ŋ ng   ɣ gh   ꞏ q   ɨ y   ə eh
#   tense (a̱) f   retroflex (ạ) c   nasal (ã) n   tone ¹ 1→';'   tone ² 2→'/'
BASE = {'ŋ': 'ng', 'ɣ': 'gh', 'ꞏ': 'q', 'ɨ': 'y', 'ə': 'eh', '¹': '1', '²': '2'}
MARK = {'̱': 'f', '̣': 'c', '̃': 'n'}


def ghc_variants(r):
    """A GHC reading may be 'zẽ(lẽ)²' (two forms) or carry '-' for a lost part."""
    r = r.strip()
    m = re.match(r'^(.*?)\((.*?)\)(.*)$', r)
    forms = [m.group(1) + m.group(3), m.group(2) + m.group(3)] if m else [r]
    return [f.replace('-', '') for f in forms if f.replace('-', '')]


def ascii_ghc(r):
    s = unicodedata.normalize('NFD', r)
    out = []
    for ch in s:
        if ch == '́':                      # acute: ś ź ń
            out.append('x')
        elif ch in MARK:
            out.append(MARK[ch])
        elif ch in BASE:
            out.append(BASE[ch])
        else:
            out.append(ch)
    a = ''.join(out)
    if not re.fullmatch(r'[a-z]+[12]?', a):
        raise ValueError(f'cannot spell {r!r} -> {a!r}')
    return a


# ---------------------------------------------------------------- weights
# No frequency list exists; a character's weight is how many dictionary words it is part of.
use = collections.Counter()
for w in WORDS:
    for c in set(w):
        use[c] += 1


def cweight(c):
    return 10 + use[c]


def radicals(code):
    return re.findall(r'[^aeiou][aeiou]+', code.replace('-', ''))


HEADER = """# Rime dictionary
# encoding: utf-8
#
# {title}
# Generated by ime/build.py from data/tangut.json (arcoinblue/wenhai-yunjing) — do not edit by hand.
# {source}
---
name: {name}
version: "{version}"
sort: by_weight
use_preset_vocabulary: false
columns:
  - text
  - code
  - weight
...
"""

os.makedirs(os.path.join(OUT, 'lua'), exist_ok=True)

# ---------------------------------------------------------------- Downes dictionary
rows = []
for c, (code, wh, mb, reads) in CH.items():
    if not code:
        continue
    rs = radicals(code)
    assert all(r in RAD_SET for r in rs), (c, code)
    rows.append((c, ' '.join(rs), cweight(c)))
with open(os.path.join(OUT, 'tangut_downes.dict.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(HEADER.format(
        title='Tangut by Downes radical code (Recursive Radical Method)',
        source='Codes: Alan Downes, Xixia Dictionaries (supplement to The Xixia Writing System, BA Hons thesis, '
               'Macquarie University, 2008); method: Downes, 递归部首法和西夏文字的结构 (2016).',
        name='tangut_downes', version=VERSION))
    for r in rows:
        f.write('%s\t%s\t%d\n' % r)
print('downes entries', len(rows))

# ---------------------------------------------------------------- GHC dictionary
ghc_rows, seen = [], set()
for c, (code, wh, mb, reads) in CH.items():
    for i, r in enumerate(reads):
        if not r[0]:
            continue
        for v in ghc_variants(r[0]):
            a = ascii_ghc(v)
            if (c, a) in seen:
                continue
            seen.add((c, a))
            ghc_rows.append((c, a, cweight(c) if i == 0 else max(1, cweight(c) // 2)))
nchar = len(ghc_rows)
skipped = 0
for w, (g, gx, en, zh) in WORDS.items():
    sy = g.split('.')
    if len(sy) != len(w) or not all(sy):
        skipped += 1
        continue
    try:
        code = ' '.join(ascii_ghc(ghc_variants(s)[0]) for s in sy)
    except (ValueError, IndexError):
        skipped += 1
        continue
    if (w, code) in seen:
        continue
    seen.add((w, code))
    ghc_rows.append((w, code, 20))
with open(os.path.join(OUT, 'tangut_ghc.dict.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(HEADER.format(
        title='Tangut by Gong Hwang-cherng (GHC) reading',
        source='Readings and words: Tangut Character Dictionary v2.2 / Tangut characters by group v2.0, '
               'as used on the Wenhai site. Spelling: see ime/README.md.',
        name='tangut_ghc', version=VERSION))
    for r in ghc_rows:
        f.write('%s\t%s\t%d\n' % r)
print('ghc entries', nchar, 'chars +', len(ghc_rows) - nchar, 'words; skipped words', skipped)

# ---------------------------------------------------------------- gloss table for the Lua filter
# key \t GHC \t Downes code \t English \t Chinese \t weight
def clean(s):
    return re.sub(r'\s+', ' ', s or '').strip()


with open(os.path.join(OUT, 'tangut_gloss.txt'), 'w', encoding='utf-8', newline='\n') as f:
    for c, (code, wh, mb, reads) in CH.items():
        ghc = ' / '.join(r[0] for r in reads if r[0])
        en = ' / '.join(dict.fromkeys(clean(r[3]) for r in reads if clean(r[3])))
        zh = ' / '.join(dict.fromkeys(clean(r[4]) for r in reads if clean(r[4])))
        f.write('\t'.join([c, ghc, code or '', en, zh, str(cweight(c))]) + '\n')
    for w, (g, gx, en, zh) in WORDS.items():
        if len(w) > 1:
            f.write('\t'.join([w, g.replace('.', ' '), '', clean(en), clean(zh), '']) + '\n')
with open(os.path.join(OUT, 'tangut_reduced.txt'), 'w', encoding='utf-8', newline='\n') as f:
    for g in GROUPS:
        f.write(' '.join(g) + '\n')

# ---------------------------------------------------------------- reduced schema (algebra from groups)
algebra = []
for g in GROUPS:
    alt = '|'.join(sorted(g, key=len, reverse=True))
    for m in g:
        algebra.append(f'    - derive/^({alt})$/{m}/')
tpl = open(os.path.join(HERE, 'templates', 'tangut_downes_reduced.schema.yaml'), encoding='utf-8').read()
open(os.path.join(OUT, 'tangut_downes_reduced.schema.yaml'), 'w', encoding='utf-8', newline='\n').write(
    tpl.replace('    # @REDUCED_ALGEBRA@', '\n'.join(algebra)).replace('@VERSION@', VERSION))
for name in ['tangut_downes.schema.yaml', 'tangut_ghc.schema.yaml']:
    s = open(os.path.join(HERE, 'templates', name), encoding='utf-8').read().replace('@VERSION@', VERSION)
    open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n').write(s)
print('reduced groups', len(GROUPS), 'rules', len(algebra))
